def test_check_coregistration_small_shift_is_aligned_and_auto_corrected():
    meta_a = validate_and_prepare(_fixture("bitemporal_before.tif"), Modality.OPTICAL, None)
    meta_b = validate_and_prepare(_fixture("bitemporal_after_small.tif"), Modality.OPTICAL, None)
    result = check_coregistration(meta_a.image_id, meta_b.image_id)

    # fixture's true shift magnitude ~ hypot(2.5, 3.0) = 3.9px
    assert result.aligned is True
    assert result.auto_corrected is True
    assert 1.0 < result.offset_px < 10.0
    assert result.reason is not None


def test_check_coregistration_large_shift_is_not_aligned():
    meta_a = validate_and_prepare(_fixture("bitemporal_before.tif"), Modality.OPTICAL, None)
    meta_b = validate_and_prepare(_fixture("bitemporal_after_large.tif"), Modality.OPTICAL, None)
    result = check_coregistration(meta_a.image_id, meta_b.image_id)

    # fixture's true shift magnitude = hypot(18, 24) = 30px
    assert result.aligned is False
    assert result.offset_px > config.COREG_MAX_ALIGNMENT_THRESHOLD_PX
    assert "refuse" in result.reason.lower() or "exceed" in result.reason.lower()


def test_check_coregistration_identical_image_against_itself_is_aligned():
    meta = validate_and_prepare(_fixture("optical_scene.tif"), Modality.OPTICAL, None)
    result = check_coregistration(meta.image_id, meta.image_id)
    assert result.aligned is True
    assert result.offset_px < config.COREG_NEGLIGIBLE_OFFSET_PX + 0.5


