def _make_tile_evidence(task, model, detections, warnings=None):
    return Evidence(
        task=task, model_used=model, modality_used=[Modality.OPTICAL],
        detections=detections, confidence=Confidence(value=0.8, band="HIGH", basis="test fixture"),
        warnings=warnings or [],
    )


def test_stitch_detections_deduplicates_overlapping_tile_boundary_detections():
    meta = validate_and_prepare(_fixture("optical_scene.tif"), Modality.OPTICAL, None)
    # simulates the same real-world building detected independently by two
    # overlapping tiles, already in full-image coordinates (as Part 4 would return)
    tile_ev_1 = _make_tile_evidence(
        TaskType.GROUNDING, "grounding-dino-mock",
        [Detection(label="building", box_px=[100, 100, 150, 150], mask_rle=None, score=0.92)],
    )
    tile_ev_2 = _make_tile_evidence(
        TaskType.GROUNDING, "grounding-dino-mock",
        [Detection(label="building", box_px=[102, 101, 152, 151], mask_rle=None, score=0.85)],
    )
    tile_ev_3 = _make_tile_evidence(
        TaskType.GROUNDING, "grounding-dino-mock",
        [Detection(label="building", box_px=[900, 900, 950, 950], mask_rle=None, score=0.7)],  # far away, distinct
    )
    merged = stitch_detections([tile_ev_1, tile_ev_2, tile_ev_3], meta.image_id)

    assert merged.task == TaskType.GROUNDING
    assert len(merged.detections) == 2  # the near-duplicate pair collapsed to 1, plus the distinct one
    scores = sorted(d.score for d in merged.detections)
    assert scores == [0.7, 0.92]  # kept the higher-scoring one of the duplicate pair


def test_stitch_detections_rejects_mixed_task_types():
    meta = validate_and_prepare(_fixture("optical_scene.tif"), Modality.OPTICAL, None)
    ev_a = _make_tile_evidence(TaskType.GROUNDING, "m", [])
    ev_b = _make_tile_evidence(TaskType.CAPTIONING, "m", [])
    with pytest.raises(ValueError):
        stitch_detections([ev_a, ev_b], meta.image_id)
