def _write_large_test_image_windowed(path: str, size: int, bands: int, block: int = 512) -> None:
    """Writes a size x size x bands uint16 GeoTIFF block-by-block via
    windowed writes, so even *generating* this fixture never holds the full
    array in memory — consistent with the same windowed-I/O discipline
    tile_image() itself is being tested for."""
    from rasterio.windows import Window

    profile = {
        "driver": "GTiff", "height": size, "width": size, "count": bands,
        "dtype": "uint16", "crs": CRS.from_epsg(32643),
        "transform": from_origin(500000.0, 2000000.0, 10.0, 10.0),
        "compress": "DEFLATE", "tiled": True, "blockxsize": block, "blockysize": block,
    }
    rng = np.random.default_rng(11)
    with rasterio.open(path, "w", **profile) as dst:
        for row_off in range(0, size, block):
            h = min(block, size - row_off)
            for col_off in range(0, size, block):
                w = min(block, size - col_off)
                chunk = rng.integers(0, 8000, size=(bands, h, w), dtype=np.uint16)
                dst.write(chunk, window=Window(col_off, row_off, w, h))


def test_tile_image_never_loads_full_array_into_memory(tmp_path):
    size, bands = 8192, 4
    large_path = str(tmp_path / "large_optical.tif")
    _write_large_test_image_windowed(large_path, size=size, bands=bands)

    meta = validate_and_prepare(large_path, Modality.OPTICAL, None)
    assert meta.is_valid, meta.validation_errors

    mem_before_kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    tiles = tile_image(meta.image_id, TaskType.GROUNDING, tile_size=1024, overlap_pct=0.1)
    mem_after_kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss

    full_array_kb = size * size * bands * 2 / 1024  # uint16 = 2 bytes/px
    additional_kb = mem_after_kb - mem_before_kb

    assert len(tiles) > 1
    assert additional_kb < full_array_kb * 0.5, (
        f"tiling used {additional_kb:.0f} KB additional peak RSS, suspiciously close to "
        f"the full array size ({full_array_kb:.0f} KB) — suggests a full-array read occurred"
    )


def test_tile_image_produces_schema_valid_tiles_covering_the_image():
    meta = validate_and_prepare(_fixture("optical_scene.tif"), Modality.OPTICAL, None)
    tiles = tile_image(meta.image_id, TaskType.GROUNDING, tile_size=256, overlap_pct=0.1)
    assert len(tiles) > 1
    for t in tiles:
        assert t.image_id == meta.image_id
        assert os.path.exists(t.array_path)
        assert len(t.affine_transform) == 6
        with rasterio.open(t.array_path) as ds:
            assert ds.width == t.width and ds.height == t.height
            arr = ds.read()
            assert arr.dtype == np.float32
            assert 0.0 <= arr.min() and arr.max() <= 1.0  # normalized


def test_tile_image_identical_grid_for_same_dimension_images():
    meta_before = validate_and_prepare(_fixture("bitemporal_before.tif"), Modality.OPTICAL, None)
    meta_after = validate_and_prepare(_fixture("bitemporal_after_small.tif"), Modality.OPTICAL, None)
    tiles_before = tile_image(meta_before.image_id, TaskType.CHANGE_DETECTION, tile_size=256, overlap_pct=0.15)
    tiles_after = tile_image(meta_after.image_id, TaskType.CHANGE_DETECTION, tile_size=256, overlap_pct=0.15)
    offsets_before = [(t.col_off, t.row_off) for t in tiles_before]
    offsets_after = [(t.col_off, t.row_off) for t in tiles_after]
    assert offsets_before == offsets_after


