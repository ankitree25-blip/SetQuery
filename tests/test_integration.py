def test_huge_declared_dims_rejected_by_pixel_cap_before_any_read():
    # ~4.1 billion declared pixels in a near-empty sparse file. If this were
    # somehow fully decoded it would be tens of GB / minutes of work -- the
    # guard must reject it fast, from metadata alone.
    import time

    t0 = time.time()
    meta = validate_and_prepare(_fixture("malformed_huge_dims.tif"), Modality.OPTICAL, None)
    elapsed = time.time() - t0

    assert meta.is_valid is False
    assert any("pixel count exceeds cap" in e for e in meta.validation_errors)
    assert meta.width == 64000 and meta.height == 64000  # the metadata probe DID read the true dims
    assert meta.cog_path == ""  # never got to COG conversion
    assert elapsed < 10, f"pixel-cap rejection took {elapsed:.1f}s — should be near-instant, metadata-only"


